/**
 * Generates both MIME tables from `mime-db`, then they are committed.
 *
 * Generated rather than hand-written because the table this replaced was a copy of
 * Apache Tomcat's `conf/web.xml` mime-mapping, vintage ~2003: it carried
 * `image/x-jg` (AOL Johnson-Grace, dead since the early 2000s) and was missing
 * `image/webp`, `image/avif`, `font/woff2`, `application/wasm` and `video/webm`.
 *
 * Committed rather than resolved at runtime so `tinita` takes no runtime dependency.
 *
 * Two tables, per owner decision QD-F (2026-10-01). Measured first: the full table
 * is 1015 types / 72KB, and `bundle: true` inlines it into every entry that imports
 * it, so a single inlined table would have cost 216KB in the tarball to replace
 * 5.8KB. The split mirrors QD-B for HTML entities.
 *
 *   src/mime/defaultTypes.ts    the types a web file utility actually handles
 *   src/mime/plugin/full.ts     all 1015, opt-in via mime.extend(full)
 *
 * Run: node scripts/generate-mime-table.mjs
 */
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const db = require('mime-db');
const dbVersion = require('mime-db/package.json').version;

const ROOT = resolve(import.meta.dirname, '..');
const MIME_DIR = resolve(ROOT, 'packages/tinita/src/mime');

/**
 * The default set, named explicitly. Extensions are still read from `mime-db`, so
 * nothing here is typed by hand - only the choice of which types to ship eagerly.
 */
const DEFAULT_TYPES = [
  // images
  'image/apng', 'image/avif', 'image/bmp', 'image/gif', 'image/heic',
  'image/heif', 'image/jpeg', 'image/png', 'image/svg+xml', 'image/tiff',
  'image/vnd.microsoft.icon', 'image/webp',
  // video
  'video/3gpp', 'video/mp4', 'video/mpeg', 'video/ogg', 'video/quicktime',
  'video/webm', 'video/x-matroska', 'video/x-msvideo',
  // audio
  'audio/aac', 'audio/x-flac', 'audio/midi', 'audio/mpeg', 'audio/ogg',
  'audio/wav', 'audio/webm', 'audio/x-m4a',
  // fonts
  'font/collection', 'font/otf', 'font/ttf', 'font/woff', 'font/woff2',
  // documents
  'application/epub+zip', 'application/msword', 'application/pdf',
  'application/rtf',
  'application/vnd.ms-excel', 'application/vnd.ms-powerpoint',
  'application/vnd.oasis.opendocument.presentation',
  'application/vnd.oasis.opendocument.spreadsheet',
  'application/vnd.oasis.opendocument.text',
  'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  // archives
  'application/gzip', 'application/vnd.rar', 'application/x-7z-compressed',
  'application/x-bzip2', 'application/x-tar', 'application/zip',
  // text and data
  'application/json', 'application/ld+json', 'application/wasm',
  'application/xml', 'application/x-sh', 'application/x-httpd-php',
  'text/calendar', 'text/css', 'text/csv', 'text/html', 'text/javascript',
  'text/markdown', 'text/plain', 'text/xml', 'text/yaml',
  // catch-all
  'application/octet-stream',
];

/**
 * Preference order when two types claim one extension, copied from the `mime-types`
 * package so the generated table agrees with the ecosystem rather than with
 * whichever type `Object.keys` happened to yield first. Later wins.
 */
const SOURCE_PREFERENCE = ['nginx', 'apache', undefined, 'iana'];

function buildTables(typeNames) {
  const toExtension = {};
  const fromExtension = {};

  for (const type of typeNames) {
    const entry = db[type];
    if (!entry?.extensions?.length) continue;

    toExtension[type] = entry.extensions[0];

    for (const extension of entry.extensions) {
      const claimed = fromExtension[extension];
      if (claimed) {
        const from = SOURCE_PREFERENCE.indexOf(db[claimed].source);
        const to = SOURCE_PREFERENCE.indexOf(entry.source);
        const keepClaimed =
          claimed !== 'application/octet-stream' &&
          (from > to || (from === to && claimed.startsWith('application/')));
        if (keepClaimed) continue;
      }
      fromExtension[extension] = type;
    }
  }

  return { toExtension, fromExtension };
}

const asRecord = (table) =>
  `{\n${Object.entries(table)
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n')}\n}`;

const header = (what, count) => `// GENERATED by scripts/generate-mime-table.mjs - do not edit by hand.
// Source: mime-db ${dbVersion}. Generated ${new Date().toISOString().slice(0, 10)}.
// ${what}: ${count} media types.
`;

// Sanity: a named default type that mime-db does not know, or knows without an
// extension, would silently vanish from the table. Fail loudly instead.
const unusable = DEFAULT_TYPES.filter((type) => !db[type]?.extensions?.length);
if (unusable.length > 0) {
  throw new Error(
    `mime-db ${dbVersion} has no extensions for: ${unusable.join(', ')}. ` +
      `Fix DEFAULT_TYPES in scripts/generate-mime-table.mjs.`
  );
}

{
  const { toExtension, fromExtension } = buildTables(DEFAULT_TYPES);
  const file = resolve(MIME_DIR, 'defaultTypes.ts');
  writeFileSync(
    file,
    `${header('Default table, the formats a web file utility handles', Object.keys(toExtension).length)}
export const DEFAULT_TYPE_TO_EXTENSION: Readonly<Record<string, string>> = ${asRecord(toExtension)};

export const DEFAULT_EXTENSION_TO_TYPE: Readonly<Record<string, string>> = ${asRecord(fromExtension)};
`
  );
  console.log(
    `defaultTypes.ts: ${Object.keys(toExtension).length} types, ${Object.keys(fromExtension).length} extensions`
  );
}

{
  const allWithExtensions = Object.keys(db).filter((type) => db[type].extensions?.length);
  const { toExtension, fromExtension } = buildTables(allWithExtensions);
  const file = resolve(MIME_DIR, 'plugin/full.ts');
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(
    file,
    `${header('Full table', Object.keys(toExtension).length)}
import type { MimePlugin } from '../types';

const TYPE_TO_EXTENSION: Readonly<Record<string, string>> = ${asRecord(toExtension)};

const EXTENSION_TO_TYPE: Readonly<Record<string, string>> = ${asRecord(fromExtension)};

/**
 * Every media type in \`mime-db\` that has a file extension.
 *
 * Opt-in because it is large. Measured: this file is the reason \`tinita/mime\` ships
 * a small default table instead - inlining the full set into all three call sites
 * cost 216KB in the tarball.
 *
 * @example
 * \`\`\`ts
 * import { mime } from 'tinita/mime';
 * import { full } from 'tinita/mime/plugin/full';
 *
 * mime.extend(full);
 * mime.fromExtension('dcurl'); // 'text/vnd.curl.dcurl'
 * \`\`\`
 */
export const full: MimePlugin = (api) => {
  api.addTypes(TYPE_TO_EXTENSION, EXTENSION_TO_TYPE);
};
`
  );
  console.log(
    `plugin/full.ts: ${Object.keys(toExtension).length} types, ${Object.keys(fromExtension).length} extensions`
  );
}
